import { execFileSync } from "node:child_process";
import { mkdirSync, renameSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";

const require = createRequire(import.meta.url);
const cli = require.resolve("supabase/dist/supabase.js");
const [command, ...options] = process.argv.slice(2);
const databaseUrl = process.env.SUPABASE_DB_URL;

function redact(value) {
  let output = String(value);
  if (databaseUrl) {
    output = output.replaceAll(databaseUrl, "[database URL]");
    try {
      const password = new URL(databaseUrl).password;
      if (password) {
        output = output.replaceAll(password, "[redacted]");
        output = output.replaceAll(decodeURIComponent(password), "[redacted]");
      }
    } catch {
      // A malformed URL is reported without including the supplied credential.
    }
  }
  return output;
}

try {
  if (databaseUrl && (command === "push" || options.includes("--remote"))) {
    let parsed;
    try {
      parsed = new URL(databaseUrl);
    } catch {
      throw new Error("SUPABASE_DB_URL must be a PostgreSQL connection URI.");
    }
    if (!["postgres:", "postgresql:"].includes(parsed.protocol)) {
      throw new Error("SUPABASE_DB_URL must be a PostgreSQL connection URI.");
    }
    const projectUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
    if (projectUrl) {
      const projectHost = new URL(projectUrl).hostname;
      if (projectHost.endsWith(".supabase.co")) {
        const projectRef = projectHost.split(".")[0];
        const direct = parsed.hostname === `db.${projectRef}.supabase.co`;
        const pooled = parsed.hostname.endsWith(".pooler.supabase.com")
          && decodeURIComponent(parsed.username) === `postgres.${projectRef}`;
        if (!direct && !pooled) {
          throw new Error("SUPABASE_DB_URL does not match the project in NEXT_PUBLIC_SUPABASE_URL.");
        }
        if (parsed.port === "6543") {
          throw new Error("Use the direct or session-pooler URI on port 5432 for migrations.");
        }
      }
    }
  }
  if (options.some((option) => !["--remote", "--dry-run"].includes(option))) {
    throw new Error("Supported options: --remote, --dry-run.");
  }
  let args;
  if (command === "types") {
    args = ["gen", "types", "typescript", "--schema", "public"];
    args.push(...(options.includes("--remote")
      ? databaseUrl ? ["--db-url", databaseUrl] : ["--linked"]
      : ["--local"]));
  } else if (command === "push") {
    args = ["db", "push", ...(databaseUrl ? ["--db-url", databaseUrl] : ["--linked"]), "--yes"];
    if (options.includes("--dry-run")) args.push("--dry-run");
  } else {
    throw new Error("Expected types or push.");
  }

  // No shell interpolation: connection strings stay in argument values. Never
  // echo the command, and redact credentials from captured CLI diagnostics.
  const output = execFileSync(process.execPath, [cli, ...args], {
    encoding: "utf8",
    maxBuffer: 20 * 1024 * 1024,
    stdio: ["ignore", "pipe", "pipe"],
    windowsHide: true,
  });
  if (command === "types") {
    if (!output.includes("export type Database =")) {
      throw new Error("The CLI did not return database types; the existing file was preserved.");
    }
    const destination = resolve("src/types/database.types.ts");
    mkdirSync(dirname(destination), { recursive: true });
    const temporary = `${destination}.tmp`;
    const normalized = output.replace(/\r\n/g, "\n").replace(/[\t ]+$/gm, "");
    writeFileSync(temporary, `// Generated by yarn db:types. Do not edit manually.\n${normalized}`);
    renameSync(temporary, destination);
    console.log("Generated src/types/database.types.ts");
  } else {
    console.log(redact(output));
  }
} catch (error) {
  console.error(redact(error.stderr?.toString() || error.message));
  process.exitCode = 1;
}
